import { Teams } from "pokemon-showdown";
import type { TeamFactory } from "@/application/ports";
import { DATA_VERSION, pickDailySpecies, type GameDate, type PokemonSet, type StatSpread, type Team } from "@/domain";
import { hashSeed } from "@/domain/rules/random";
import { dex, GEN, LAST_DEX_NUMBER } from "./generation";

const LEGENDARY_TAGS = ["Restricted Legendary", "Sub-Legendary", "Mythical"];

type Species = ReturnType<typeof dex.species.get>;

function isFinalForm(species: Species): boolean {
  // Evolutions from later generations (Sylveon, Annihilape...) don't count.
  return !(species.evos ?? []).some((evo: string) => {
    const next = dex.species.get(evo);
    return next.exists && next.num <= LAST_DEX_NUMBER;
  });
}

/** Whether the Random Battle generator has competitive sets for the species (Unown doesn't). */
function hasGeneratedSets(species: Species): boolean {
  try {
    Teams.getGenerator(`gen${GEN}randombattle`, toSodiumSeed("probe")).randomSet(species, {}, false);
    return true;
  } catch {
    return false;
  }
}

/**
 * Every fully evolved, non-legendary Pokémon up to Gen 4 (base formes only).
 * Pokémon that gained an evolution in Gen 4 are replaced by it (Murkrow → Honchkrow,
 * Electabuzz → Electivire). Pikachu is out (it evolves); Raichu is in. No stat cap.
 */
export function buildPlayerPool(): string[] {
  return dex.species
    .all()
    .filter(
      (s) =>
        s.exists &&
        s.num >= 1 &&
        s.num <= LAST_DEX_NUMBER &&
        !s.forme &&
        s.baseSpecies === s.name &&
        !s.tags.some((t) => LEGENDARY_TAGS.includes(t)) &&
        isFinalForm(s) &&
        hasGeneratedSets(s),
    )
    .map((s) => s.name)
    .sort();
}

/**
 * Items that lock the holder into a single move (the Choice items). Competitive, but
 * they make the daily team feel restrictive, so they become Leftovers — a common
 * second choice on those sets, and one that keeps all four moves usable.
 */
const MOVE_LOCKING_ITEMS = new Set(["Choice Band", "Choice Specs", "Choice Scarf"]);
const LOCKING_ITEM_REPLACEMENT = "Leftovers";

function playableItem(item: string): string {
  return MOVE_LOCKING_ITEMS.has(item) ? LOCKING_ITEM_REPLACEMENT : item;
}

function toSodiumSeed(seed: string) {
  const hex = [0, 1, 2, 3].map((i) => hashSeed(`${seed}#${i}`).toString(16).padStart(8, "0")).join("");
  return `sodium,${hex}` as const;
}

interface GeneratedSet {
  species: string;
  item: string;
  ability: string;
  nature?: string;
  evs?: Partial<StatSpread>;
  ivs?: Partial<StatSpread>;
  moves: string[];
}

/**
 * The day's team: species picked by the domain rule, builds generated by Showdown's
 * Random Battle set generator of the generation (competitive sets maintained by the community),
 * seeded by the date so everyone gets the same builds. All at level 100.
 */
export class ShowdownTeamFactory implements TeamFactory {
  private readonly pool = buildPlayerPool();
  private readonly cache = new Map<GameDate, Team>();

  poolSpecies(): readonly string[] {
    return this.pool;
  }

  dailyTeam(date: GameDate): Team {
    const cached = this.cache.get(date);
    if (cached) return structuredClone(cached);

    const species = pickDailySpecies(date, this.pool);
    const generator = Teams.getGenerator(`gen${GEN}randombattle`, toSodiumSeed(`${date}:sets:v${DATA_VERSION}`));
    const team = species.map((name) => this.toSet(name, generator.randomSet(dex.species.get(name), {}, false) as GeneratedSet));

    if (this.cache.size > 30) this.cache.clear();
    this.cache.set(date, team);
    return structuredClone(team);
  }

  private toSet(species: string, generated: GeneratedSet): PokemonSet {
    const ivs = Object.fromEntries(Object.entries(generated.ivs ?? {}).filter(([, v]) => v !== 31));
    return {
      // The generator may return a cosmetic forme ("Unown-D"); keep the pool's base species.
      species,
      item: playableItem(dex.items.get(generated.item).name || ""),
      ability: dex.abilities.get(generated.ability).name,
      // Random Battle sets don't use natures; a neutral one keeps their EV math intact.
      nature: generated.nature || "Hardy",
      evs: generated.evs ?? {},
      ...(Object.keys(ivs).length > 0 ? { ivs } : {}),
      moves: generated.moves.map((id) => dex.moves.get(id).name),
    };
  }
}
